import assert from "node:assert/strict";
import { CommunicationProtocolEnum, DaprClient } from "@dapr/dapr";

const client = new DaprClient({
  daprHost: process.env.DAPR_HOST ?? "localhost",
  daprPort: process.env.DAPR_HTTP_PORT ?? "3500",
  communicationProtocol: CommunicationProtocolEnum.HTTP,
});
const store = "vectorstore";
const collection = "catalog";
const writeOptions = {
  mode: "waitForCompletion",
  waitTimeout: "5s",
  onWaitTimeout: "failRequest",
};

async function main() {
  try {
    await client.vector.createCollection(store, collection, { dimensions: 3, metric: "cosine" });
    const info = await client.vector.getCollection(store, collection);
    assert.equal(info.dimensions, 3);
    assert.equal(info.metric, "cosine");
    console.log(`Created collection: ${info.collection} (${info.dimensions} dimensions, ${info.metric})`);

    const collections = await client.vector.listCollections(store);
    assert.ok(collections.includes(collection));
    console.log(`Collection listed: ${collection}`);

    // These fixed vectors stand in for embeddings generated by your application.
    const records = [
      {
        id: "book-1",
        values: [1, 0, 0],
        payload: Buffer.from("Dapr for beginners"),
        metadata: { category: "book" },
      },
      { id: "book-2", values: [0.8, 0.6, 0], metadata: { category: "book" } },
      { id: "toy-1", values: [0, 1, 0], metadata: { category: "toy" } },
    ];
    const upsert = await client.vector.upsertVectors(store, collection, records, writeOptions);
    assert.deepEqual(upsert.failedItems, []);
    assert.equal(upsert.ack, "completed");
    console.log(`Upserted vectors: ${records.length} (${upsert.ack})`);

    const retrieved = await client.vector.getVectors(store, collection, ["book-1"], { includeValues: true });
    assert.equal(retrieved.length, 1);
    const record = retrieved[0];
    assert.deepEqual(record.values, [1, 0, 0]);
    assert.equal(record.metadata.category, "book");
    assert.equal(Buffer.from(record.payload).toString(), "Dapr for beginners");
    console.log(`Retrieved vector: ${record.id} [${record.values.join(",")}]`);
    console.log(`Retrieved payload: ${Buffer.from(record.payload).toString()}`);

    const nearest = await client.vector.queryVectors(store, collection, { vector: [1, 0, 0], topK: 2 });
    assert.equal(nearest.metric, "cosine");
    assert.deepEqual(nearest.matches.map(match => match.record.id), ["book-1", "book-2"]);
    assert.ok(Math.abs(nearest.matches[0].score - 1) < 0.000001);
    assert.ok(Math.abs(nearest.matches[1].score - 0.8) < 0.000001);
    console.log(`Nearest vectors: ${nearest.matches.map(match => match.record.id).join(", ")}`);

    const filtered = await client.vector.queryVectors(store, collection, {
      byId: "book-1",
      topK: 2,
      filter: { category: { $eq: "toy" } },
    });
    assert.deepEqual(filtered.matches.map(match => match.record.id), ["toy-1"]);
    console.log(`Filtered vectors: ${filtered.matches.map(match => match.record.id).join(", ")}`);

    const batch = await client.vector.batchQueryVectors(store, collection, [
      { vector: [1, 0, 0], topK: 1 },
      { vector: [0, 1, 0], topK: 1 },
    ]);
    for (const result of batch) {
      if (result.error) {
        throw new Error(`Batch query failed: ${JSON.stringify(result.error)}`);
      }
    }
    const batchIds = batch.map(result => result.response.matches[0].record.id);
    assert.deepEqual(batchIds, ["book-1", "toy-1"]);
    console.log(`Batch nearest vectors: ${batchIds.join(", ")}`);

    const ack = await client.vector.deleteVectors(store, collection, records.map(item => item.id), writeOptions);
    assert.equal(ack, "completed");
    const remaining = await client.vector.getVectors(store, collection, records.map(item => item.id));
    assert.deepEqual(remaining, []);
    console.log(`Vectors after deletion: ${remaining.length}`);

    await client.vector.deleteCollection(store, collection);
    const afterDeletion = await client.vector.listCollections(store);
    assert.ok(!afterDeletion.includes(collection));
    console.log(`Deleted collection: ${collection}`);
  } finally {
    await client.stop();
  }
  console.log("Vector quickstart completed");
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
