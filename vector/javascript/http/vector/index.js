import assert from "node:assert/strict";

const daprHost = process.env.DAPR_HOST ?? "localhost";
const daprPort = process.env.DAPR_HTTP_PORT ?? "3500";
const collectionsUrl = `http://${daprHost}:${daprPort}/v1.0-alpha1/vector/vectorstore/collections`;
const collection = "catalog";
const collectionPath = `/${collection}`;
const writeOptions = {
  mode: "INDEXING_MODE_WAIT_FOR_COMPLETION",
  waitTimeout: "5s",
  onWaitTimeout: "INDEXING_WAIT_TIMEOUT_ACTION_FAIL_REQUEST",
};

async function request(method, path, body) {
  const response = await fetch(`${collectionsUrl}${path}`, {
    method,
    headers: { "Content-Type": "application/json" },
    body: body === undefined ? undefined : JSON.stringify(body),
    signal: AbortSignal.timeout(10000),
  });
  const text = await response.text();
  if (!response.ok) {
    throw new Error(`${method} ${path} failed (${response.status}): ${text}`);
  }
  return text ? JSON.parse(text) : undefined;
}

async function main() {
  await request("POST", collectionPath, {
    dimensions: 3,
    metric: "DISTANCE_METRIC_COSINE",
  });
  const info = await request("GET", collectionPath);
  assert.equal(info.dimensions, 3);
  assert.equal(info.metric, "DISTANCE_METRIC_COSINE");
  console.log(`Created collection: ${info.collection} (${info.dimensions} dimensions, cosine)`);

  const { collections } = await request("GET", "");
  assert.ok(collections.includes(collection));
  console.log(`Collection listed: ${collection}`);

  // These fixed vectors stand in for embeddings generated by your application.
  const records = [
    {
      id: "book-1",
      values: [1, 0, 0],
      payload: Buffer.from("Dapr for beginners").toString("base64"),
      metadata: { category: "book" },
    },
    { id: "book-2", values: [0.8, 0.6, 0], metadata: { category: "book" } },
    { id: "toy-1", values: [0, 1, 0], metadata: { category: "toy" } },
  ];
  const upsert = await request("POST", `${collectionPath}/vectors`, { records, options: writeOptions });
  assert.deepEqual(upsert.failedItems, []);
  assert.equal(upsert.ack, "INDEX_ACK_COMPLETED");
  console.log(`Upserted vectors: ${records.length} (completed)`);

  const retrieved = await request("POST", `${collectionPath}/vectors/get`, {
    ids: ["book-1"],
    includeValues: true,
  });
  assert.equal(retrieved.records.length, 1);
  const record = retrieved.records[0];
  assert.deepEqual(record.values, [1, 0, 0]);
  assert.equal(record.metadata.category, "book");
  assert.equal(Buffer.from(record.payload, "base64").toString(), "Dapr for beginners");
  console.log(`Retrieved vector: ${record.id} [${record.values.join(",")}]`);
  console.log(`Retrieved payload: ${Buffer.from(record.payload, "base64").toString()}`);

  const nearest = await request("POST", `${collectionPath}/query`, {
    query: { vector: { values: [1, 0, 0] }, topK: 2 },
  });
  assert.equal(nearest.metric, "DISTANCE_METRIC_COSINE");
  assert.deepEqual(nearest.matches.map(match => match.record.id), ["book-1", "book-2"]);
  assert.ok(Math.abs(nearest.matches[0].score - 1) < 0.000001);
  assert.ok(Math.abs(nearest.matches[1].score - 0.8) < 0.000001);
  console.log(`Nearest vectors: ${nearest.matches.map(match => match.record.id).join(", ")}`);

  const filtered = await request("POST", `${collectionPath}/query`, {
    query: { byId: "book-1", topK: 2, filter: { category: { $eq: "toy" } } },
  });
  assert.deepEqual(filtered.matches.map(match => match.record.id), ["toy-1"]);
  console.log(`Filtered vectors: ${filtered.matches.map(match => match.record.id).join(", ")}`);

  const batch = await request("POST", `${collectionPath}/batch-query`, {
    queries: [
      { vector: { values: [1, 0, 0] }, topK: 1 },
      { vector: { values: [0, 1, 0] }, topK: 1 },
    ],
  });
  for (const result of batch.results) {
    if (result.error) {
      throw new Error(`Batch query failed: ${JSON.stringify(result.error)}`);
    }
  }
  const batchIds = batch.results.map(result => result.response.matches[0].record.id);
  assert.deepEqual(batchIds, ["book-1", "toy-1"]);
  console.log(`Batch nearest vectors: ${batchIds.join(", ")}`);

  const deleted = await request("POST", `${collectionPath}/vectors/delete`, {
    ids: records.map(item => item.id),
    options: writeOptions,
  });
  assert.equal(deleted.ack, "INDEX_ACK_COMPLETED");
  const remaining = await request("POST", `${collectionPath}/vectors/get`, {
    ids: records.map(item => item.id),
  });
  assert.deepEqual(remaining.records, []);
  console.log(`Vectors after deletion: ${remaining.records.length}`);

  await request("DELETE", collectionPath);
  const afterDeletion = await request("GET", "");
  assert.ok(!afterDeletion.collections.includes(collection));
  console.log(`Deleted collection: ${collection}`);
  console.log("Vector quickstart completed");
}

main().catch(error => {
  console.error(error);
  process.exitCode = 1;
});
