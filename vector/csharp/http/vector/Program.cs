using System.Net.Http.Json;
using System.Text;
using System.Text.Json;

var daprHost = Environment.GetEnvironmentVariable("DAPR_HOST") ?? "localhost";
var daprPort = Environment.GetEnvironmentVariable("DAPR_HTTP_PORT") ?? "3500";
using var httpClient = new HttpClient
{
    BaseAddress = new Uri($"http://{daprHost}:{daprPort}/v1.0-alpha1/vector/vectorstore/collections/"),
    Timeout = TimeSpan.FromSeconds(10)
};
const string collection = "catalog";
var writeOptions = new
{
    mode = "INDEXING_MODE_WAIT_FOR_COMPLETION",
    waitTimeout = "5s",
    onWaitTimeout = "INDEXING_WAIT_TIMEOUT_ACTION_FAIL_REQUEST"
};

await SendAsync(HttpMethod.Post, collection, new { dimensions = 3, metric = "DISTANCE_METRIC_COSINE" });
var info = JsonSerializer.Deserialize<JsonElement>(await SendAsync(HttpMethod.Get, collection));
Require(info.GetProperty("dimensions").GetInt32() == 3 &&
        info.GetProperty("metric").GetString() == "DISTANCE_METRIC_COSINE", "Unexpected collection settings.");
Console.WriteLine($"Created collection: {info.GetProperty("collection").GetString()} (3 dimensions, cosine)");

var listed = JsonSerializer.Deserialize<JsonElement>(await SendAsync(HttpMethod.Get, ""));
Require(listed.GetProperty("collections").EnumerateArray().Any(item => item.GetString() == collection),
    "Created collection was not listed.");
Console.WriteLine($"Collection listed: {collection}");

// These fixed vectors stand in for embeddings generated by your application.
object[] records =
[
    new
    {
        id = "book-1",
        values = new[] { 1f, 0f, 0f },
        payload = Convert.ToBase64String(Encoding.UTF8.GetBytes("Dapr for beginners")),
        metadata = new { category = "book" }
    },
    new { id = "book-2", values = new[] { 0.8f, 0.6f, 0f }, metadata = new { category = "book" } },
    new { id = "toy-1", values = new[] { 0f, 1f, 0f }, metadata = new { category = "toy" } }
];
var upsert = JsonSerializer.Deserialize<JsonElement>(
    await SendAsync(HttpMethod.Post, $"{collection}/vectors", new { records, options = writeOptions }));
Require(upsert.GetProperty("failedItems").GetArrayLength() == 0, $"Vector upsert failed: {upsert}");
Require(upsert.GetProperty("ack").GetString() == "INDEX_ACK_COMPLETED", "Vector upsert did not complete.");
Console.WriteLine($"Upserted vectors: {records.Length} (completed)");

var retrieved = JsonSerializer.Deserialize<JsonElement>(
    await SendAsync(HttpMethod.Post, $"{collection}/vectors/get", new { ids = new[] { "book-1" }, includeValues = true }));
Require(retrieved.GetProperty("records").GetArrayLength() == 1, "Expected one retrieved vector.");
var record = retrieved.GetProperty("records")[0];
Require(record.GetProperty("values").EnumerateArray().Select(value => value.GetSingle()).SequenceEqual([1f, 0f, 0f]),
    "Retrieved vector values did not match.");
Require(record.GetProperty("metadata").GetProperty("category").GetString() == "book", "Metadata did not round-trip.");
var payload = Encoding.UTF8.GetString(record.GetProperty("payload").GetBytesFromBase64());
Require(payload == "Dapr for beginners", "Payload did not round-trip.");
Console.WriteLine($"Retrieved vector: {record.GetProperty("id").GetString()} [1,0,0]");
Console.WriteLine($"Retrieved payload: {payload}");

var nearest = JsonSerializer.Deserialize<JsonElement>(await SendAsync(HttpMethod.Post, $"{collection}/query",
    new { query = new { vector = new { values = new[] { 1f, 0f, 0f } }, topK = 2 } }));
var nearestIds = MatchIds(nearest);
Require(nearest.GetProperty("metric").GetString() == "DISTANCE_METRIC_COSINE", "Unexpected query metric.");
Require(nearestIds.SequenceEqual(["book-1", "book-2"]), "Unexpected nearest vectors or ranking.");
Require(Math.Abs(nearest.GetProperty("matches")[0].GetProperty("score").GetDouble() - 1) < 0.000001 &&
        Math.Abs(nearest.GetProperty("matches")[1].GetProperty("score").GetDouble() - 0.8) < 0.000001,
    "Unexpected cosine scores.");
Console.WriteLine($"Nearest vectors: {string.Join(", ", nearestIds)}");

var filtered = JsonSerializer.Deserialize<JsonElement>(await SendAsync(HttpMethod.Post, $"{collection}/query",
    new
    {
        query = new
        {
            byId = "book-1",
            topK = 2,
            filter = JsonSerializer.Deserialize<JsonElement>("""{"category":{"$eq":"toy"}}""")
        }
    }));
var filteredIds = MatchIds(filtered);
Require(filteredIds.SequenceEqual(["toy-1"]), "Metadata filter did not exclude books.");
Console.WriteLine($"Filtered vectors: {string.Join(", ", filteredIds)}");

var batch = JsonSerializer.Deserialize<JsonElement>(await SendAsync(HttpMethod.Post, $"{collection}/batch-query",
    new
    {
        queries = new[]
        {
            new { vector = new { values = new[] { 1f, 0f, 0f } }, topK = 1 },
            new { vector = new { values = new[] { 0f, 1f, 0f } }, topK = 1 }
        }
    }));
var batchIds = new List<string?>();
foreach (var result in batch.GetProperty("results").EnumerateArray())
{
    if (result.TryGetProperty("error", out var error))
    {
        throw new InvalidOperationException($"Batch query failed: {error}");
    }
    batchIds.Add(MatchIds(result.GetProperty("response")).Single());
}
Require(batchIds.SequenceEqual(["book-1", "toy-1"]), "Unexpected batch results or ordering.");
Console.WriteLine($"Batch nearest vectors: {string.Join(", ", batchIds)}");

string[] ids = ["book-1", "book-2", "toy-1"];
var deleted = JsonSerializer.Deserialize<JsonElement>(
    await SendAsync(HttpMethod.Post, $"{collection}/vectors/delete", new { ids, options = writeOptions }));
Require(deleted.GetProperty("ack").GetString() == "INDEX_ACK_COMPLETED", "Vector deletion did not complete.");
var remaining = JsonSerializer.Deserialize<JsonElement>(
    await SendAsync(HttpMethod.Post, $"{collection}/vectors/get", new { ids }));
var remainingCount = remaining.GetProperty("records").GetArrayLength();
Require(remainingCount == 0, "Deleted vectors were still retrievable.");
Console.WriteLine($"Vectors after deletion: {remainingCount}");

await SendAsync(HttpMethod.Delete, collection);
var afterDeletion = JsonSerializer.Deserialize<JsonElement>(await SendAsync(HttpMethod.Get, ""));
Require(!afterDeletion.GetProperty("collections").EnumerateArray().Any(item => item.GetString() == collection),
    "Deleted collection was still listed.");
Console.WriteLine($"Deleted collection: {collection}");
Console.WriteLine("Vector quickstart completed");

async Task<string> SendAsync(HttpMethod method, string path, object? body = null)
{
    using var request = new HttpRequestMessage(method, path);
    if (body is not null)
    {
        request.Content = JsonContent.Create(body);
    }
    using var response = await httpClient.SendAsync(request);
    var text = await response.Content.ReadAsStringAsync();
    if (!response.IsSuccessStatusCode)
    {
        throw new HttpRequestException($"{method} {path} failed ({response.StatusCode}): {text}");
    }
    return text;
}

static string?[] MatchIds(JsonElement result) =>
    result.GetProperty("matches").EnumerateArray()
        .Select(match => match.GetProperty("record").GetProperty("id").GetString()).ToArray();

static void Require(bool condition, string message)
{
    if (!condition)
    {
        throw new InvalidOperationException(message);
    }
}
