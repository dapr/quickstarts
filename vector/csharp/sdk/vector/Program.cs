using System.Text;
using System.Text.Json;
using Dapr.Vector;

using var client = new DaprVectorClientBuilder().Build();
using var timeout = new CancellationTokenSource(TimeSpan.FromSeconds(30));
var ct = timeout.Token;
const string store = "vectorstore";
const string collection = "catalog";
var writeOptions = new IndexingOptions
{
    Mode = IndexingMode.WaitForCompletion,
    WaitTimeout = TimeSpan.FromSeconds(5),
    OnWaitTimeout = IndexingWaitTimeoutAction.FailRequest
};

await client.CreateCollectionAsync(store, collection, 3, DistanceMetric.Cosine, cancellationToken: ct);
var info = await client.GetCollectionAsync(store, collection, cancellationToken: ct);
Require(info.Dimensions == 3 && info.Metric == DistanceMetric.Cosine, "Unexpected collection settings.");
Console.WriteLine($"Created collection: {info.Collection} ({info.Dimensions} dimensions, cosine)");

var collections = await client.ListCollectionsAsync(store, cancellationToken: ct);
Require(collections.Contains(collection), "Created collection was not listed.");
Console.WriteLine($"Collection listed: {collection}");

// byte[] payloads are transferred unchanged; other payload types use the SDK's JSON serializer.
// These fixed vectors stand in for embeddings generated by your application.
VectorRecord<byte[]>[] records =
[
    new("book-1", [1, 0, 0], Encoding.UTF8.GetBytes("Dapr for beginners"),
        JsonSerializer.SerializeToElement(new { category = "book" })),
    new("book-2", [0.8f, 0.6f, 0], Metadata: JsonSerializer.SerializeToElement(new { category = "book" })),
    new("toy-1", [0, 1, 0], Metadata: JsonSerializer.SerializeToElement(new { category = "toy" }))
];
var upsert = await client.UpsertVectorsAsync(store, collection, records, writeOptions, cancellationToken: ct);
Require(upsert.FailedItems.Count == 0, $"Vector upsert failed: {JsonSerializer.Serialize(upsert.FailedItems)}");
Require(upsert.Ack == IndexAck.Completed, "Vector upsert did not complete.");
Console.WriteLine($"Upserted vectors: {records.Length} (completed)");

var retrieved = await client.GetVectorsAsync<byte[]>(store, collection, ["book-1"],
    includeValues: true, cancellationToken: ct);
var record = retrieved.Single();
Require(record.Values.SequenceEqual([1f, 0f, 0f]), "Retrieved vector values did not match.");
Require(record.Metadata?.GetProperty("category").GetString() == "book", "Metadata did not round-trip.");
var payload = Encoding.UTF8.GetString(record.Payload ?? throw new InvalidOperationException("Missing payload."));
Require(payload == "Dapr for beginners", "Payload did not round-trip.");
Console.WriteLine($"Retrieved vector: {record.Id} [1,0,0]");
Console.WriteLine($"Retrieved payload: {payload}");

var nearest = await client.QueryVectorsAsync<byte[]>(store, collection,
    new VectorQuery { Vector = [1, 0, 0], TopK = 2 }, cancellationToken: ct);
var nearestIds = nearest.Matches.Select(match => match.Record.Id).ToArray();
Require(nearest.Metric == DistanceMetric.Cosine, "Unexpected query metric.");
Require(nearestIds.SequenceEqual(["book-1", "book-2"]), "Unexpected nearest vectors or ranking.");
Require(Math.Abs(nearest.Matches[0].Score - 1) < 0.000001 &&
        Math.Abs(nearest.Matches[1].Score - 0.8) < 0.000001, "Unexpected cosine scores.");
Console.WriteLine($"Nearest vectors: {string.Join(", ", nearestIds)}");

var filtered = await client.QueryVectorsAsync<byte[]>(store, collection, new VectorQuery
{
    ById = "book-1",
    TopK = 2,
    Filter = JsonSerializer.Deserialize<JsonElement>("""{"category":{"$eq":"toy"}}""")
}, cancellationToken: ct);
var filteredIds = filtered.Matches.Select(match => match.Record.Id).ToArray();
Require(filteredIds.SequenceEqual(["toy-1"]), "Metadata filter did not exclude books.");
Console.WriteLine($"Filtered vectors: {string.Join(", ", filteredIds)}");

var batch = await client.BatchQueryVectorsAsync<byte[]>(store, collection,
[
    new VectorQuery { Vector = [1, 0, 0], TopK = 1 },
    new VectorQuery { Vector = [0, 1, 0], TopK = 1 }
], cancellationToken: ct);
var batchIds = new List<string>();
foreach (var result in batch)
{
    if (result.Error is { } error)
    {
        throw new InvalidOperationException($"Batch query failed ({error.Code}): {error.Message}");
    }
    var response = result.Response ?? throw new InvalidOperationException("Missing batch query response.");
    batchIds.Add(response.Matches.Single().Record.Id);
}
Require(batchIds.SequenceEqual(["book-1", "toy-1"]), "Unexpected batch results or ordering.");
Console.WriteLine($"Batch nearest vectors: {string.Join(", ", batchIds)}");

var ids = records.Select(item => item.Id).ToArray();
var ack = await client.DeleteVectorsAsync(store, collection, ids, writeOptions, cancellationToken: ct);
Require(ack == IndexAck.Completed, "Vector deletion did not complete.");
var remaining = await client.GetVectorsAsync<byte[]>(store, collection, ids, cancellationToken: ct);
Require(remaining.Count == 0, "Deleted vectors were still retrievable.");
Console.WriteLine($"Vectors after deletion: {remaining.Count}");

await client.DeleteCollectionAsync(store, collection, cancellationToken: ct);
var afterDeletion = await client.ListCollectionsAsync(store, cancellationToken: ct);
Require(!afterDeletion.Contains(collection), "Deleted collection was still listed.");
Console.WriteLine($"Deleted collection: {collection}");
Console.WriteLine("Vector quickstart completed");

static void Require(bool condition, string message)
{
    if (!condition)
    {
        throw new InvalidOperationException(message);
    }
}
